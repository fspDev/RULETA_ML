// Transform para que las letras rectas ocupen exactamente la caja (x, tope) → (x + ancho, ...),
// con el alto que corresponda a ese ancho.
export function encajarHoySePide(x, tope, ancho) {
  const s = ancho / HSP_ANCHO;
  return `translate(${x} ${tope - HSP_TOPE * s}) scale(${s})`;
}
